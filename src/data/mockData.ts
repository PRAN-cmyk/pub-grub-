// Distinctive and sharp SVG avatar generator ensuring ZERO broken external URLs
export const createAvatarUrl = (name: string, bg: string, text: string) => {
  const initials = name
    .split(' ')
    .map((n) => n[0])
    .join('')
    .slice(0, 2)
    .toUpperCase();
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
    <rect width="100" height="100" rx="50" fill="${bg}" />
    <text x="50" y="55" font-family="-apple-system, BlinkMacSystemFont, sans-serif" font-size="38" font-weight="700" fill="${text}" dominant-baseline="middle" text-anchor="middle">${initials}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
};

